// Synthetic demo dataset generator.
//
// Every fact in this directory is invented for demonstration and testing: the
// city, operator, line and station names, the topology, the mileage and the
// coordinates do not describe any real network, and no content is copied from
// the maintainers' internal data packages. The generator is the single source
// of the committed demo files; re-run it after editing the dataset below:
//
//   node demo/generate.mjs
//
// It writes a reduced (simulated) scenario archive plus the browser envelope
// that tools/prepare-web-assets.mjs publishes for local development.
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodeReducedEnvelope } from '../packages/application/reduced-input.mjs';

const demoRoot = fileURLToPath(new URL('.', import.meta.url));
const scenarioDirectory = join(demoRoot, 'scenarios', 'demo-reduced');
const envelopeDirectory = join(demoRoot, 'envelopes');

export const SNAPSHOT_ID = 'simulated-demo-0001';
const SNAPSHOT_AS_OF = '2024-06-01';
const KNOWLEDGE_THROUGH = '2030-12-31';

const sha256 = text => createHash('sha256').update(text, 'utf8').digest('hex');
const fileEntry = text => ({ bytes: Buffer.byteLength(text, 'utf8'), sha256: sha256(text) });

const PERIOD = { valid_from: '2018-01-01', valid_to: null };
const DEMO_NOTICE = `# Demo data notice

This directory contains **synthetic demo data only**. It is generated by
\`demo/generate.mjs\` from an invented dataset: there is no real network,
station, mileage, coordinate or operator data in it.

The file name \`LICENSE-OSM.md\` is required by the reduced-envelope schema,
which reuses the envelope field names of the licensed-data pipeline. No
OpenStreetMap data or attribution is included, and nothing here is derived
from OpenStreetMap.

The dataset may be used freely for running and testing this project.
`;

const city = { id: 'demo-city', name: '示例城' };
const operator = { id: 'demo-op', name: '示例轨道交通', type: 'metro_company', city_id: 'demo-city' };

/** Station order is chosen so that the two physical lines share one interchange. */
const stationSpecs = [
  ['demo-s01', 'D01', '青松', 31.201, 121.401],
  ['demo-s02', 'D02', '云岭', 31.206, 121.405],
  ['demo-s03', 'D03', '石桥', 31.212, 121.409],
  ['demo-s04', 'D04', '河湾', 31.218, 121.414],
  ['demo-s05', 'D05', '白鹭', 31.224, 121.419],
  ['demo-s06', 'D06', '东浦', 31.230, 121.424],
  ['demo-s07', 'D07', '松林', 31.236, 121.429],
  ['demo-s08', 'D08', '望江', 31.242, 121.434],
  ['demo-s09', 'D09', '枫岸', 31.222, 121.421],
  ['demo-s10', 'D10', '芦滩', 31.226, 121.428],
  ['demo-s11', 'D11', '潮汐', 31.230, 121.435],
  ['demo-s12', 'D12', '灯塔', 31.234, 121.442],
  ['demo-s13', 'D13', '沙洲', 31.238, 121.449],
];

const stations = stationSpecs.map(([id, code, name, latitude, longitude]) => ({
  id, station_code: code, name, city_id: 'demo-city', lat: latitude, lng: longitude,
}));

const lineSpecs = [
  {
    id: 'demo-line-1', name: '一号线', from: 'demo-s01', to: 'demo-s08', sections: 7,
    directionLabels: [
      { label: '青松 → 望江', from_station_id: 'demo-s01', to_station_id: null },
      { label: '望江 → 青松', from_station_id: 'demo-s08', to_station_id: null },
    ],
  },
  {
    id: 'demo-line-2', name: '二号线', from: 'demo-s04', to: 'demo-s13', sections: 5,
    directionLabels: [
      { label: '河湾 → 沙洲', from_station_id: 'demo-s04', to_station_id: null },
      { label: '沙洲 → 河湾', from_station_id: 'demo-s13', to_station_id: null },
    ],
  },
];

const physicalLines = lineSpecs.map(spec => ({
  id: spec.id, name: spec.name, ...PERIOD, is_loop: false, loop_fold_station_id: null,
  direction_labels: spec.directionLabels,
}));

/** Consecutive station path per physical line; the first line starts at demo-s01, the second at demo-s04. */
const sectionPaths = [
  ['demo-s01', 'demo-s02', 'demo-s03', 'demo-s04', 'demo-s05', 'demo-s06', 'demo-s07', 'demo-s08'],
  ['demo-s04', 'demo-s09', 'demo-s10', 'demo-s11', 'demo-s12', 'demo-s13'],
];

const sections = [];
const memberships = [];
for (const [lineIndex, spec] of lineSpecs.entries()) {
  const path = sectionPaths[lineIndex];
  for (let index = 0; index < spec.sections; index += 1) {
    const id = `demo-l${lineIndex + 1}-s${String(index + 1).padStart(2, '0')}`;
    sections.push({
      id, physical_line_id: spec.id, from_station_id: path[index], to_station_id: path[index + 1], ...PERIOD,
      length_m: 1200 + lineIndex * 200 + index * 100, length_source: 'demo-synthetic',
    });
    memberships.push({ service_line_id: `demo-service-${lineIndex + 1}`, physical_section_id: id, seq: index, ...PERIOD });
  }
}

const services = lineSpecs.map((spec, index) => ({
  id: `demo-service-${index + 1}`, name: spec.name, operator_id: 'demo-op', ...PERIOD,
  direction_labels: spec.directionLabels,
}));

const reader = {
  schema_version: 'phase1.transit-reader.v1',
  snapshot_id: SNAPSHOT_ID,
  source_status: 'simulated',
  as_of: SNAPSHOT_AS_OF,
  entities: {
    cities: [city],
    operators: [operator],
    stations,
    physical_lines: physicalLines,
    physical_sections: sections,
    service_lines: services,
    service_line_sections: memberships,
    station_names: stations.map(row => ({ station_id: row.id, name: row.name, ...PERIOD })),
    station_service_periods: stations.map(row => ({ station_id: row.id, kind: 'passenger', ...PERIOD })),
    section_mappings: [],
    topology_events: [],
  },
};

const sourceUse = {
  schema_version: 'demo-reduced-source-use.v1',
  source_status: 'simulated',
  release_ready: false,
  synthetic: true,
  notice: 'Synthetic demo dataset generated by demo/generate.mjs; no real-world network data.',
  inherited_base_data_use: {
    attribution: { text: 'Synthetic demo data — fictional network, no real-world data.' },
    coordinates: { provider: 'demo-generator', coordinate_system: 'WGS-84' },
    license: { name: 'Demo-Only-1.0', url: 'https://example.invalid/demo-license' },
  },
};

const policies = {
  schema_version: 'demo-reduced-policies.v1',
  no_mileage_operators: [],
  permanent_closures: [],
  temporary_suspensions: [],
};

export async function generate() {
  const files = {
    'source-use.json': JSON.stringify(sourceUse, null, 2),
    'policies.json': JSON.stringify(policies, null, 2),
    'reader-payload.json': JSON.stringify(reader, null, 2),
    'LICENSE-OSM.md': DEMO_NOTICE,
  };
  const manifestText = JSON.stringify({
    schema_version: 'noritsubushi-reduced-scenario.v1',
    source_status: 'simulated',
    release_ready: false,
    snapshot_id: SNAPSHOT_ID,
    snapshot_as_of: SNAPSHOT_AS_OF,
    knowledge_through: KNOWLEDGE_THROUGH,
    coverage_from: SNAPSHOT_AS_OF,
    coverage_to: KNOWLEDGE_THROUGH,
    synthetic: true,
    notice: 'Synthetic demo dataset; see demo/README.md. No real data is included.',
    files: Object.fromEntries(Object.entries(files).map(([name, text]) => [name, fileEntry(text)])),
  }, null, 2);

  const envelopeText = JSON.stringify({
    schema_version: 'phase1.application-input.reduced.v1',
    manifest: manifestText,
    sourceUse: files['source-use.json'],
    policies: files['policies.json'],
    reader: files['reader-payload.json'],
    license: files['LICENSE-OSM.md'],
  });

  // Refuse to commit demo data the real decoder would reject.
  const decoded = await decodeReducedEnvelope(envelopeText, sha256(envelopeText));
  if (decoded.network.snapshotId !== SNAPSHOT_ID || decoded.network.stations.length !== stations.length ||
    decoded.network.sections.length !== sections.length || decoded.network.services.length !== services.length) {
    throw new Error('Generated demo envelope does not decode to the intended synthetic network');
  }

  const reviewedMapping = {
    [SNAPSHOT_ID]: { snapshots: [], stationSplits: [], throughServicePairs: [] },
  };

  await mkdir(scenarioDirectory, { recursive: true });
  await mkdir(envelopeDirectory, { recursive: true });
  for (const [name, text] of Object.entries(files)) await writeFile(join(scenarioDirectory, name), text);
  await writeFile(join(scenarioDirectory, 'manifest.json'), manifestText);
  await writeFile(join(envelopeDirectory, 'reduced-envelope.json'), envelopeText);
  await writeFile(join(envelopeDirectory, 'reviewed-mapping.json'), JSON.stringify(reviewedMapping, null, 2));

  return { envelopeDigest: sha256(envelopeText), envelopeBytes: Buffer.byteLength(envelopeText, 'utf8'),
    stations: stations.length, sections: sections.length, services: services.length, snapshotId: SNAPSHOT_ID };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const summary = await generate();
  console.log(`Demo dataset ready: ${summary.stations} stations, ${summary.sections} sections, `
    + `${summary.services} services, snapshot ${summary.snapshotId}`);
  console.log(`Envelope digest ${summary.envelopeDigest} (${summary.envelopeBytes} bytes)`);
}
