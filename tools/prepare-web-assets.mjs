// Publish application envelopes for the web app.
//
// This public repository does not contain the licensed-data exporter. It
// consumes *pre-generated* envelopes instead, so the same command works for
// the demo dataset and for a private data root supplied by the maintainers:
//
//   node tools/prepare-web-assets.mjs
//   NORITSU_DATA_ROOT=<data-root> node tools/prepare-web-assets.mjs
//
// A data root must provide:
//   envelopes/reduced-envelope.json      required for the demo (simulated) input
//   envelopes/development-envelope.json  optional, only with a licensed data root
//   envelopes/reviewed-mapping.json      optional cross-snapshot whitelist
//
// Envelopes are decoded here before anything is published, so a corrupt or
// unverifiable envelope stops the command instead of reaching the browser.
import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodeApplicationEnvelope } from '../packages/application/development-input.mjs';
import { decodeReducedEnvelope } from '../packages/application/reduced-input.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const publicDirectory = resolve(root, 'apps/web/public/application-input');
const generatedDirectory = resolve(root, 'apps/web/.generated');
const dataRoot = process.env.NORITSU_DATA_ROOT
  ? resolve(root, process.env.NORITSU_DATA_ROOT)
  : resolve(root, 'demo');
const envelopeDirectory = join(dataRoot, 'envelopes');
const digest = text => createHash('sha256').update(text, 'utf8').digest('hex');

// Only the two directories this generator owns are touched. Never clean a data
// root, and refuse a linked directory instead of writing through it.
for (const directory of [publicDirectory, generatedDirectory]) {
  await mkdir(directory, { recursive: true });
  if ((await lstat(directory)).isSymbolicLink()) throw new Error(`Refusing linked generated directory: ${directory}`);
}

const ENVELOPE_KINDS = {
  'phase1.application-input.v1': {
    sourceKind: 'real-internal-test', filePrefix: 'envelope',
    filename: 'development-envelope.json', decode: decodeApplicationEnvelope,
  },
  'phase1.application-input.reduced.v1': {
    sourceKind: 'simulated', filePrefix: 'reduced',
    filename: 'reduced-envelope.json', decode: decodeReducedEnvelope,
  },
};

async function optionalText(name) {
  try {
    return await readFile(join(envelopeDirectory, name), 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

/** Decode one envelope and stage its published file; returns the asset row. */
async function publish(text) {
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new Error(`Envelope in ${envelopeDirectory} is not valid JSON`);
  }
  const kind = ENVELOPE_KINDS[parsed.schema_version];
  if (kind === undefined) {
    throw new Error(`Unsupported envelope schema_version: ${String(parsed.schema_version)}`);
  }
  const sha256 = digest(text);
  const { network } = await kind.decode(text, sha256);
  const name = `${kind.filePrefix}-${sha256}.json`;
  const staging = join(publicDirectory, `${name}.tmp`);
  await writeFile(staging, text);
  await rename(staging, join(publicDirectory, name));
  return { url: `application-input/${name}`, sha256, sourceKind: kind.sourceKind, snapshotId: network.snapshotId };
}

const reducedText = await optionalText(ENVELOPE_KINDS['phase1.application-input.reduced.v1'].filename);
const developmentText = await optionalText(ENVELOPE_KINDS['phase1.application-input.v1'].filename);
if (reducedText === null && developmentText === null) {
  throw new Error(`No pre-generated application envelope found in ${envelopeDirectory}. `
    + 'This repository ships a synthetic demo dataset (re-create it with node demo/generate.mjs); '
    + 'point NORITSU_DATA_ROOT at a data root that provides envelopes/ to build a licensed input.');
}
const assets = [];
if (developmentText !== null) assets.push(await publish(developmentText));
if (reducedText !== null) assets.push(await publish(reducedText));

const reviewedText = await optionalText('reviewed-mapping.json');
let reviewedMapping = {};
if (reviewedText !== null) {
  try {
    reviewedMapping = JSON.parse(reviewedText);
  } catch {
    throw new Error(`reviewed-mapping.json in ${envelopeDirectory} is not valid JSON`);
  }
  if (reviewedMapping === null || typeof reviewedMapping !== 'object' || Array.isArray(reviewedMapping)) {
    throw new Error('reviewed-mapping.json must contain an object keyed by target snapshot id');
  }
}

const assetsText = `// Generated by tools/prepare-web-assets.mjs; do not edit.\n`
  + `export const inputAssets = ${JSON.stringify(assets)} as const;\n`;
const reviewedSource = `// Generated by tools/prepare-web-assets.mjs; do not edit.\n`
  + `// Empty unless the data root supplies envelopes/reviewed-mapping.json; keys are TARGET snapshot ids.\n`
  + `export const reviewedMapping = ${JSON.stringify(reviewedMapping)} as const;\n`;
const assetsStaging = join(generatedDirectory, 'input-asset.ts.tmp');
const reviewedStaging = join(generatedDirectory, 'reviewed-mapping.ts.tmp');
await writeFile(assetsStaging, assetsText);
await writeFile(reviewedStaging, reviewedSource);
await rename(assetsStaging, join(generatedDirectory, 'input-asset.ts'));
await rename(reviewedStaging, join(generatedDirectory, 'reviewed-mapping.ts'));

// Remove only envelope files this generator owns; anything else in the
// published directory is left alone.
const keep = new Set(assets.map(asset => asset.url.split('/').at(-1)));
for (const name of await readdir(publicDirectory)) {
  if ((/^envelope-[a-f0-9]{64}\.json$/.test(name) || /^reduced-[a-f0-9]{64}\.json$/.test(name)) && !keep.has(name)) {
    const path = join(publicDirectory, name);
    if ((await lstat(path)).isFile()) await rm(path);
  }
}

console.log(`Prepared ${assets.length} application asset(s) from ${dataRoot}`);
for (const asset of assets) console.log(`  ${asset.sourceKind} ${asset.snapshotId} -> ${asset.url} (${asset.sha256})`);
