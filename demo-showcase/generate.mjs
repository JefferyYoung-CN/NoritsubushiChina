// network, and nothing is copied from the maintainers' internal data packages.
// This dataset exists so the public app can show every feature it implements:
//
//   - an east-west line and a north-south line meeting at an interchange
//   - a loop line (physical_lines.is_loop plus a fold station)
//   - a line with a branch (one physical line, two service lines)
//   - two service lines that share sections (line 3 and its branch run-in)
//   - declared through-running pairs (line 3 / branch, express / intercity)
//   - a temporary suspension that is still open, one already resumed
//   - a permanently closed line and a permanently closed mid-line section
//   - an operator without mileage, one city-crossing line, a renamed station
//   - a station that is not served by passenger trains
//   - three duplicate-name groups that exercise each disambiguation layer
//     (city, operator, line set) plus one that only collides before 2022
//
