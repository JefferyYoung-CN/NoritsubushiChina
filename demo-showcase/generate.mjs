export async function generate() {
  return writeReducedScenario({
    root: showcaseRoot,
    scenario: 'demo-showcase-full',
    snapshotId: SNAPSHOT_ID,
    snapshotAsOf: SNAPSHOT_AS_OF,
    knowledgeThrough: KNOWLEDGE_THROUGH,
    reader, sourceUse, policies, reviewedMapping,
    notice: NOTICE,
    manifestNotice: 'Synthetic showcase dataset; see demo-showcase/README.md. No real data is included.',
  });
}

